#!/usr/bin/env bash
# changed-packages.test.sh — the contract of test selection by reverse closure.
#
# `changed-packages.sh` answers two different questions from one diff:
#   - lint scope: the packages the author touched;
#   - test scope: every package that can BREAK because of them.
# The second is a closure over the import graph, and getting it wrong is silent
# in the expensive direction: too narrow and the suite is green while a caller
# is broken; too wide and a two-package PR pays for the whole module again.
#
# These cases pin the narrowing on a throwaway module with a known graph:
#
#   leaf <- mid <- top                (production imports)
#   leaf <- testonly                  (in-package test import: TestImports)
#   leaf <- xtestonly                 (external test package: XTestImports)
#   templpage <- templuser            (linked only through a .templ change)
#   unrelated                         (nothing imports it, it imports nothing)
#
# Every expectation is spelled as an ABSOLUTE path, which is also the assertion
# that the output keeps the shape `go test` and `golangci-lint` accept.
#
# Runs in a few seconds, no network: the fixture imports nothing but stdlib.
set -euo pipefail

SCRIPT="$(cd "$(dirname "$0")" && pwd)/changed-packages.sh"
TMP="$(mktemp -d)"
trap 'rm -rf "${TMP}"' EXIT

FX="${TMP}/fixture"
FX_NOGIT="${TMP}/no-git"

fail() {
    echo "✗ $1" >&2
    exit 1
}

# Offline and workspace-free: the fixture must not inherit a go.work or flags
# from whatever ran this script.
fixture_env() {
    ( cd "$1" && shift && GOWORK=off GOFLAGS= GOTOOLCHAIN=local "$@" )
}

# Run the real script with the fixture as the project root.
scope() {
    local dir="$1"; shift
    ( cd "$dir" && GOWORK=off GOFLAGS= bash "${SCRIPT}" "$@" 2>/dev/null )
}

# Same run, keeping only what it said on stderr.
scope_stderr() {
    local dir="$1"; shift
    ( cd "$dir" && GOWORK=off GOFLAGS= bash "${SCRIPT}" "$@" 2>&1 >/dev/null )
}

assert_set() {
    local name="$1" actual="$2"; shift 2
    local expected sorted
    expected=$(printf '%s\n' "$@" | sed '/^$/d' | sort)
    sorted=$(printf '%s\n' "$actual" | sed '/^$/d' | sort)
    if [ "${sorted}" != "${expected}" ]; then
        echo "✗ ${name}" >&2
        diff -u \
            <(printf '%s\n' "${expected}" | sed 's/^/  expected: /') \
            <(printf '%s\n' "${sorted}" | sed 's/^/  actual:   /') >&2 || true
        exit 1
    fi
    echo "  ✓ ${name}"
}

assert_empty() {
    local name="$1" actual="$2"
    if [ -n "$(printf '%s' "${actual}" | tr -d '[:space:]')" ]; then
        echo "✗ ${name}" >&2
        printf '%s\n' "${actual}" | sed 's/^/  actual:   /' >&2
        exit 1
    fi
    echo "  ✓ ${name}"
}

# ── the fixture: a module whose graph is known by construction ──
build_fixture() {
    local d
    for d in leaf mid top testonly xtestonly templpage templuser unrelated; do
        mkdir -p "${FX}/${d}"
    done

    cat > "${FX}/go.mod" <<'EOF'
module example.test/fixture

go 1.21
EOF

    cat > "${FX}/leaf/leaf.go" <<'EOF'
package leaf

func Leaf() string { return "leaf" }
EOF

    cat > "${FX}/mid/mid.go" <<'EOF'
package mid

import "example.test/fixture/leaf"

func Mid() string { return leaf.Leaf() }
EOF

    cat > "${FX}/mid/mid2.go" <<'EOF'
package mid

func Mid2() string { return "mid2" }
EOF

    cat > "${FX}/top/top.go" <<'EOF'
package top

import "example.test/fixture/mid"

func Top() string { return mid.Mid() }
EOF

    # Dependency through an in-package test file: net/http's httptest pattern.
    cat > "${FX}/testonly/testonly.go" <<'EOF'
package testonly

func Nothing() {}
EOF
    cat > "${FX}/testonly/leaf_test.go" <<'EOF'
package testonly

import (
	"testing"

	"example.test/fixture/leaf"
)

func TestLeaf(t *testing.T) { _ = leaf.Leaf() }
EOF

    # Dependency through an external test package (foo_test): the shape of an
    # integration test that exercises a package from outside.
    cat > "${FX}/xtestonly/xtestonly.go" <<'EOF'
package xtestonly

func Nothing() {}
EOF
    cat > "${FX}/xtestonly/leaf_test.go" <<'EOF'
package xtestonly_test

import (
	"testing"

	"example.test/fixture/leaf"
)

func TestLeaf(t *testing.T) { _ = leaf.Leaf() }
EOF

    # A page: only the .templ is edited, the generated _templ.go is committed
    # and is regenerated by `make templ` — so the .templ must seed on its own.
    cat > "${FX}/templpage/page.go" <<'EOF'
package templpage

func Page() string { return "<p>page</p>" }
EOF
    cat > "${FX}/templpage/page.templ" <<'EOF'
package templpage

templ Page() {
	<p>page</p>
}
EOF

    cat > "${FX}/templuser/user.go" <<'EOF'
package templuser

import "example.test/fixture/templpage"

func User() string { return templpage.Page() }
EOF

    cat > "${FX}/unrelated/unrelated.go" <<'EOF'
package unrelated

func Unrelated() {}
EOF

    cat > "${FX}/Makefile" <<'EOF'
all:
	@echo ok
EOF

    local git=(git -C "${FX}" -c user.email=test@example.test -c user.name=test)
    "${git[@]}" init -q
    "${git[@]}" add -A
    "${git[@]}" commit -qm "fixture"
    "${git[@]}" tag base
}

reset_fixture() {
    git -C "${FX}" checkout -q -- .
    git -C "${FX}" clean -qfd
}

touch_file() {
    printf '\n// touched by the test\n' >> "${FX}/$1"
}

all_fixture_packages() {
    fixture_env "${FX}" go list -f '{{.Dir}}' ./... | sort
}

echo "changed-packages: reverse dependency closure"

# ── 1. nothing changed → nothing to run ──
build_fixture
assert_empty "a clean tree outputs nothing" "$(scope "${FX}" --with-dependents)"

# ── 2. the default stays lint-shaped: the touched package only ──
# Lint scope is deliberately NOT transitive (lint what you touched); this case
# is the regression guard for every caller of the no-flag form.
reset_fixture
touch_file leaf/leaf.go
assert_set "without the flag a touched leaf yields only leaf" \
    "$(scope "${FX}")" \
    "${FX}/leaf"

# ── 3. a touched leaf pulls every transitive dependent, and nothing else ──
assert_set "a touched leaf pulls its transitive dependents" \
    "$(scope "${FX}" --with-dependents)" \
    "${FX}/leaf" "${FX}/mid" "${FX}/top" "${FX}/testonly" "${FX}/xtestonly"

# ── 4. closure follows imports, not dependencies ──
# mid imports leaf, so leaf must stay out; top imports mid, so top must be in.
reset_fixture
touch_file mid/mid.go
assert_set "a touched mid pulls top but not leaf" \
    "$(scope "${FX}" --with-dependents)" \
    "${FX}/mid" "${FX}/top"

# ── 5. a .templ change seeds its own package before `make templ` runs ──
reset_fixture
printf '\n<!-- touched -->\n' >> "${FX}/templpage/page.templ"
assert_set "a touched .templ pulls its package and its dependents" \
    "$(scope "${FX}" --with-dependents)" \
    "${FX}/templpage" "${FX}/templuser"

# …and does not leak into lint scope, which is Go-only by design.
assert_empty "without the flag a .templ change yields nothing" \
    "$(scope "${FX}")"

# ── 6. shared plumbing invalidates everything (fail-open) ──
reset_fixture
printf '\n# touched\n' >> "${FX}/Makefile"
mapfile -t ALL_PKGS < <(all_fixture_packages)
[ "${#ALL_PKGS[@]}" -ge 8 ] || fail "expected at least 8 fixture packages, got ${#ALL_PKGS[@]}"
assert_set "a shared file change falls back to every package" \
    "$(scope "${FX}" --with-dependents)" \
    "${ALL_PKGS[@]}"

# ── 7. BASE carries committed work on the branch ──
reset_fixture
touch_file leaf/leaf.go
git -C "${FX}" -c user.email=test@example.test -c user.name=test commit -qam "touch leaf"
assert_set "BASE adds the branch's committed changes" \
    "$(cd "${FX}" && GOWORK=off GOFLAGS= BASE=base bash "${SCRIPT}" --with-dependents 2>/dev/null)" \
    "${FX}/leaf" "${FX}/mid" "${FX}/top" "${FX}/testonly" "${FX}/xtestonly"

# ── 8. a DELETED file still seeds its package ──
# `[ -f "$f" ]` is false for a deletion, so a naive seed loop drops it and the
# caller of the deleted package is never re-tested.
reset_fixture
rm "${FX}/mid/mid.go"
assert_set "a deleted file seeds its package and its dependents" \
    "$(scope "${FX}" --with-dependents)" \
    "${FX}/mid" "${FX}/top"

# …and when the deletion takes the whole package, nothing can place the seed in
# the dependency order any more, so the answer is every package (`go list -e`
# keeps the graph readable while the import of the deleted package is broken).
rm "${FX}/mid/mid2.go"
mapfile -t REMAINING < <(printf '%s\n' "${ALL_PKGS[@]}" | grep -vx "${FX}/mid")
assert_set "a deleted package widens to every remaining package" \
    "$(scope "${FX}" --with-dependents)" \
    "${REMAINING[@]}"
# The widening must be the closure's decision, not a failed listing: a module
# whose import is already broken must still be graphable (`go list -e`), or the
# selection is a guess dressed as an answer.
case "$(scope_stderr "${FX}" --with-dependents)" in
    *"cannot list the package graph"*) fail "the package graph must stay readable while an import is broken" ;;
esac

# ── 9. an unreadable tree widens instead of narrowing ──
# No .git at all: test selection cannot know what moved, so it must not guess.
git -C "${FX}" reset -q --hard base
mkdir -p "${FX_NOGIT}"
( cd "${FX}" && tar -cf - --exclude=.git . ) | ( cd "${FX_NOGIT}" && tar -xf - )
mapfile -t ALL_NOGIT < <(fixture_env "${FX_NOGIT}" go list -f '{{.Dir}}' ./... | sort)
assert_set "a tree without git falls back to every package" \
    "$(scope "${FX_NOGIT}" --with-dependents)" \
    "${ALL_NOGIT[@]}"

echo "✅ changed-packages contract holds"
