// Installer engine: the genui/chat built-in unit (data only)
//
// Split out of trim_features.go for the file-size gate. genui is the AI
// bundle: chat imports genui components (no-compile without it), so the two
// are one unit (see the genui capability entry). Chat mounts itself via
// Register (panels arrive through Deps.Panels); the root builds the todo
// panel the catalog installs.

package installer

// genuiBuiltinUnits holds the one AI unit. A slice (not a bare literal) so
// builtin_units.go appends it the same way it appends featureBuiltinUnits.
//
// The import lines are consts because the unit drops them from two files
// (chi.go and chi_test.go) and goconst is right that one spelling beats two
// literals: a rename that missed one would leave a dangling import in the
// trimmed tree.
const (
	genuiComponentsImp = `comp "github.com/calionauta/gogogo/features/genui/components"`
	// configPageTempl is the admin page both the components section and the
	// sounds trim address: one spelling so a rename cannot strand a rule.
	configPageTempl = "features/config/components/page.templ"
)

var genuiBuiltinUnits = []builtinUnit{
	{
		id: unitGenUI,
		// Bundle rationale lives in the genui capability entry: chat imports
		// genui components (no-compile without it), so one unit is the only
		// honest shape (see internal/capabilities).
		extraStrips: []fileStrip{
			{
				// The panel branches in the todo mutations go with the unit:
				// they answer through panel_action.go, which the unit deletes
				// (its Files entry), so a trimmed tree must not call it. The
				// page paths they wrap stay byte-identical. One rule covers
				// all nine regions (toggle/delete × target/read/save/outcome):
				// markers match by substring, so repeats are stripped too.
				path: "features/todo/handlers/mutations.go",
				rules: []stripRule{
					{
						startMarker: "// trim-genui:panel:start",
						endMarker:   "// trim-genui:panel:end",
					},
				},
			},
			{
				// The panel's slice-tab branch in the list route answers
				// through answerPanelList (panel_action.go), so it leaves with
				// the unit; the page's own filter/scope path stays as it was.
				path: "features/todo/handlers/chi.go",
				rules: []stripRule{
					{
						startMarker: "// trim-genui:panel:start",
						endMarker:   "// trim-genui:panel:end",
					},
				},
			},
			{
				// The config page's answer-catalog helpers go with the unit:
				// without the registry they reference a package the trimmed
				// tree deleted. Two rules (one func each): a brace match stops
				// at the first func's end, so one rule cannot span both.
				path: "features/config/components/safe_view.go",
				rules: []stripRule{
					{
						startMarker:       "// catalogInfos lists the generative answer components",
						endIsClosingBrace: true,
						endBrace:          "}",
					},
					{
						startMarker:       "// panelInfos lists the installed native panels",
						endIsClosingBrace: true,
						endBrace:          "}",
					},
				},
			},
			{
				// The config page's answer-components section renders PageData
				// the trimmed tree no longer fills — strip it, markers
				// included. templ is regenerated by the trim prove step, so
				// no _templ.go edits.
				path: configPageTempl,
				rules: []stripRule{
					{
						startMarker: "<!-- trim-genui:components-section:start -->",
						endMarker:   "<!-- trim-genui:components-section:end -->",
					},
				},
			},
			{
				// The sidebar renders []Module, so the trimmed Chat
				// destination is one dropped entry.
				path:  modulesFile,
				rules: []stripRule{{startMarker: `{ID: "chat"`, endMarker: "},"}},
			},
		},
		extraDrops: []fileDrop{
			{
				path: chiGoFile,
				substrs: []string{
					// The todo panel the chat unit installs globally:
					// without genui there is no catalog, so the root stops
					// building it and stops passing Panels.
					"panels := []any{todohandlers.NewTodoPanel(queries, slots)}",
					"Panels: panels,",
				},
			},
			{
				// The config page's answer-components section is wired from
				// the catalog: without the unit the fields have no type and
				// the wiring has no callee. The strip rules above remove the
				// helpers and the section; these drops remove the import, the
				// two fields (+ their doc line) and the two wiring lines. The
				// status strip has no genui dependency and stays.
				path: "features/config/components/safe_view.go",
				substrs: []string{
					genuiComponentsImp,
					"AnswerCatalog",
					"AnswerPanels",
				},
			},
			{
				// strings.Join lives only in the stripped components section.
				path: configPageTempl,
				substrs: []string{
					`"strings"`,
				},
			},
			{
				// The mux table's "/chat" element goes too (one element per
				// line, so combined trims stay order-independent). Chat
				// mounts via the seam now; there is no handler construction
				// left in this test file.
				path: chiTestFile,
				substrs: []string{
					"\t\t\"/chat\",",
				},
			},
		},
	},
}
