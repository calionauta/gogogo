// SCOPE:plugin — installer engine: rename moves the paths, not only the text
package installer

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// TestRenameTreeMovesNameBearingPaths is the guard for the half-renamed tree.
//
// The content pass rewrites every REFERENCE to a name-bearing path (`go run
// ./cmd/gogogo`, `cmd/gogogo-mcp/go.mod`, `skills/gogogo-coding-standards/
// SKILL.md`). If the directories keep the template name, every one of those
// references points at nothing — and nothing notices, because the build proof
// never opens them. What fails later is a test that does, with "no such file",
// in a project whose own name is the only clue.
func TestRenameTreeMovesNameBearingPaths(t *testing.T) {
	root := t.TempDir()

	files := map[string]string{
		"go.mod":                "module github.com/calionauta/gogogo\n\ngo 1.27\n",
		"README.md":             "run `go run ./cmd/gogogo`, then `cd cmd/gogogo-mcp`\n",
		"cmd/gogogo/main.go":    "package main\n\nfunc main() {}\n",
		"cmd/gogogo-mcp/go.mod": "module github.com/calionauta/gogogo/cmd/gogogo-mcp\n",
		"cmd/web/main.go":       "package main\n",
		"skills/gogogo-coding-standards/SKILL.md": "# skill\n",
		// Vendored upstream skills keep their upstream names in every
		// checkout: only gogogo-coding-standards carries the project name.
		// A rename must leave their paths AND their bytes alone.
		"skills/daisyui/SKILL.md":                          "# daisyui\n",
		"skills/daisyui/UPSTREAM_SHA":                      "abc123\n",
		"skills/stelow-workflow-coding-standards/SKILL.md": "# stelow\n",
		// Generated by site/build.mjs: a name-bearing file here must be left
		// alone (it is regenerated), exactly like the content pass leaves it.
		"site/docs/gogogo-coding-standards.md": "generated\n",
	}
	for rel, body := range files {
		writeFile(t, filepath.Join(root, filepath.FromSlash(rel)), body)
	}

	if err := renameTree(root, "my-app", "me"); err != nil {
		t.Fatalf("renameTree: %v", err)
	}

	for _, gone := range []string{
		"cmd/gogogo",
		"cmd/gogogo-mcp",
		"skills/gogogo-coding-standards",
	} {
		if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(gone))); !os.IsNotExist(err) {
			t.Errorf("%s still exists (err=%v) — the path must move with the text", gone, err)
		}
	}
	for _, want := range []string{
		"cmd/my-app/main.go",
		"cmd/my-app-mcp/go.mod",
		"skills/my-app-coding-standards/SKILL.md",
		"cmd/web/main.go",
	} {
		if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(want))); err != nil {
			t.Errorf("%s missing after the rename: %v", want, err)
		}
	}

	// A directory that moved must not move again: cmd/my-app-mcp, never
	// cmd/my-app-mcp-mcp.
	for _, bad := range []string{"cmd/my-app-mcp-mcp", "cmd/my-app-app"} {
		if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(bad))); err == nil {
			t.Errorf("%s exists — a path was moved twice", bad)
		}
	}

	if _, err := os.Stat(filepath.Join(root, "site", "docs", "gogogo-coding-standards.md")); err != nil {
		t.Errorf("generated site/docs was moved or removed: %v", err)
	}

	// Vendored skills survive the rename byte-identical: the pin names the
	// upstream content, so a rewrite would make it a lie.
	for rel, want := range map[string]string{
		"skills/daisyui/SKILL.md":                          "# daisyui\n",
		"skills/daisyui/UPSTREAM_SHA":                      "abc123\n",
		"skills/stelow-workflow-coding-standards/SKILL.md": "# stelow\n",
	} {
		got, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
		if err != nil {
			t.Errorf("%s missing after the rename: %v", rel, err)
			continue
		}
		if string(got) != want {
			t.Errorf("%s was rewritten by the rename: %q", rel, got)
		}
	}

	readme, err := os.ReadFile(filepath.Join(root, "README.md"))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(readme), "cmd/gogogo") {
		t.Errorf("the README still names a path that no longer exists:\n%s", readme)
	}
	if !strings.Contains(string(readme), "./cmd/my-app") {
		t.Errorf("the README reference was not rewritten:\n%s", readme)
	}
}
