// TestRenameTreeMovesNameBearingPaths is the guard for the half-renamed tree.
//
// The content pass rewrites every REFERENCE to a name-bearing path (`go run
// ./cmd/gogogo`, `cmd/gogogo-mcp/README.md`, `skills/gogogo-coding-standards/
// SKILL.md`). If the directories keep the template name, every one of those
// references points at nothing — and nothing notices, because the build proof
// never opens them. What fails later is a test that does, with "no such file",
// in a project whose own name is the only clue.
func TestRenameTreeMovesNameBearingPaths(t *testing.T) {
	// These assertions name the TEMPLATE's own paths, so they only mean
	// something in the template: a scaffolded product already renamed them.
	requireTemplateIdentity(t)
	root := t.TempDir()

	files := map[string]string{
		"go.mod":                   "module github.com/calionauta/gogogo\n\ngo 1.27\n",
		"README.md":                "run `go run ./cmd/gogogo`, then `cd cmd/gogogo-mcp`\n",
		"cmd/gogogo/main.go":       "package main\n\nfunc main() {}\n",
		"cmd/gogogo-mcp/README.md": "the MCP server\n",
		"cmd/web/main.go":          "package main\n",
		"skills/gogogo-coding-standards/SKILL.md": "# skill\n",
		// Vendored upstream skills keep their upstream names in every
		// checkout: only gogogo-coding-standards carries the project name.
		// A rename must leave their paths AND their bytes alone.
		"skills/daisyui/SKILL.md":                          "# daisyui\n",
		"skills/daisyui/UPSTREAM_SHA":                      "abc123\n",
		"skills/stelow-workflow-coding-standards/SKILL.md": "# stelow\n",
		// Generated by site/build.mjs: a name-bearing file here must be left
		// alone (it is regenerated), exactly like the content pass leaves it.
		"site/docs/gogogo-coding-standards.md": "generated\n",
	}
	for rel, body := range files {
		writeFile(t, filepath.Join(root, filepath.FromSlash(rel)), body)
	}

	if err := renameTree(root, "my-app", "me"); err != nil {
		t.Fatalf("renameTree: %v", err)
	}

	for _, gone := range []string{
		"cmd/gogogo",
		"cmd/gogogo-mcp",
		"skills/gogogo-coding-standards",
	} {
		if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(gone))); !os.IsNotExist(err) {
			t.Errorf("%s still exists (err=%v) — the path must move with the text", gone, err)
		}
	}
	for _, want := range []string{
		"cmd/my-app/main.go",
		"cmd/my-app-mcp/README.md",
		"skills/my-app-coding-standards/SKILL.md",
		"cmd/web/main.go",
	} {
		if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(want))); err != nil {
			t.Errorf("%s missing after the rename: %v", want, err)
		}
	}

	// A directory that moved must not move again: cmd/my-app-mcp, never
	// cmd/my-app-mcp-mcp.
	for _, bad := range []string{"cmd/my-app-mcp-mcp", "cmd/my-app-app"} {
		if _, err := os.Stat(filepath.Join(root, filepath.FromSlash(bad))); err == nil {
			t.Errorf("%s exists — a path was moved twice", bad)
		}
	}

	if _, err := os.Stat(filepath.Join(root, "site", "docs", "gogogo-coding-standards.md")); err != nil {
		t.Errorf("generated site/docs was moved or removed: %v", err)
	}

	// Vendored skills survive the rename byte-identical: the pin names the
	// upstream content, so a rewrite would make it a lie.
	for rel, want := range map[string]string{
		"skills/daisyui/SKILL.md":                          "# daisyui\n",
		"skills/daisyui/UPSTREAM_SHA":                      "abc123\n",
		"skills/stelow-workflow-coding-standards/SKILL.md": "# stelow\n",
	} {
		got, err := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
		if err != nil {
			t.Errorf("%s missing after the rename: %v", rel, err)
			continue
		}
		if string(got) != want {
			t.Errorf("%s was rewritten by the rename: %q", rel, got)
		}
	}

	readme, err := os.ReadFile(filepath.Join(root, "README.md"))
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(readme), "cmd/gogogo") {
		t.Errorf("the README still names a path that no longer exists:\n%s", readme)
	}
	if !strings.Contains(string(readme), "./cmd/my-app") {
		t.Errorf("the README reference was not rewritten:\n%s", readme)
	}
}

// TestRenameTreeSecondHopReadsTheTreeItIsIn is the two-hop guard.
//
// A scaffold rewrites the tree's identity, and the tree it produces is itself a
// template: its tool scaffolds the next product. That only works if the rename
// asks the tree what it is called instead of trusting a constant compiled into
// the binary. It used to trust three constants and the rewrite caught two of
// them, so a fork renamed nothing on the second hop and cloned the template's
// org. The identity comes from go.mod now; this drives two hops in one process,
// which a constant could never survive.
func TestRenameTreeSecondHopReadsTheTreeItIsIn(t *testing.T) {
	root := t.TempDir()
	writeFile(t, filepath.Join(root, "go.mod"), "module github.com/calionauta/gogogo\n\ngo 1.27\n")
	identity := "package installer\n\nconst (\n\ttemplateOwner = \"calionauta\"\n\ttemplateRepo  = \"gogogo\"\n)\n"
	writeFile(t, filepath.Join(root, "internal/installer/run.go"), identity)
	writeFile(t, filepath.Join(root, "cmd/gogogo/main.go"), "package main\n")

	if err := renameTree(root, "hopb", "e2e"); err != nil {
		t.Fatalf("hop 1: %v", err)
	}
	assertRenameIdentity(t, root, "github.com/e2e/hopb", `templateOwner = "e2e"`, `templateRepo  = "hopb"`)

	// Hop 2: the same function, on the tree hop 1 produced, with no constant
	// rewritten. This is the call a product's own tool makes.
	if err := renameTree(root, "hopc", "acme"); err != nil {
		t.Fatalf("hop 2: %v", err)
	}
	assertRenameIdentity(t, root, "github.com/acme/hopc", `templateOwner = "acme"`, `templateRepo  = "hopc"`)

	// Nothing may still name the intermediate product.
	var stale []string
	if err := walkRenameTree(root, func(rel string, _ os.FileInfo) error {
		raw, rerr := os.ReadFile(filepath.Join(root, filepath.FromSlash(rel)))
		if rerr == nil && strings.Contains(string(raw), "hopb") {
			stale = append(stale, rel)
		}
		return nil
	}); err != nil {
		t.Fatalf("walk: %v", err)
	}
	if len(stale) > 0 {
		t.Fatalf("hop 2 left the intermediate name in: %v", stale)
	}
}

// assertRenameIdentity checks the module line and the tool's own constants.
func assertRenameIdentity(t *testing.T, root, module, ownerConst, repoConst string) {
	t.Helper()
	gomod, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(string(gomod), "module "+module+"\n") {
		t.Fatalf("go.mod = %q, want module %s", string(gomod), module)
	}
	run, err := os.ReadFile(filepath.Join(root, "internal/installer/run.go"))
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{ownerConst, repoConst} {
		if !strings.Contains(string(run), want) {
			t.Fatalf("run.go is missing %q:\n%s", want, run)
		}
	}
}

// TestRenameNamesTheConsumerMCPAfterTheProduct pins the naming contract:
//
//	template:  cmd/product-mcp   (a PLACEHOLDER — the template is not a product)
//	product:   cmd/<product>-mcp (that product's own name)
//
// without the second, every generated product would install a binary called
// `product-mcp`, and two of them on one PATH would collide. And the identity
// the server reports must follow, or two products announce themselves to an
// agent under the same name.
func TestRenameNamesTheConsumerMCPAfterTheProduct(t *testing.T) {
	requireTemplateIdentity(t)
	root := t.TempDir()

	files := map[string]string{
		"go.mod":                  "module github.com/calionauta/gogogo\n\ngo 1.27\n",
		"cmd/product-mcp/main.go": "package main\n\nfunc main() {}\n",
		"cmd/product-mcp/doc.go":  "// doc\n",
		"cmd/web/main.go":         "package main\n",
	}
	for rel, body := range files {
		writeFile(t, filepath.Join(root, filepath.FromSlash(rel)), body)
	}
	if err := renameTree(root, "xpto", "acme"); err != nil {
		t.Fatalf("renameTree: %v", err)
	}

	if _, err := os.Stat(filepath.Join(root, "cmd", "xpto-mcp", "main.go")); err != nil {
		t.Fatalf("cmd/xpto-mcp/main.go missing after rename: %v", err)
	}
	if _, err := os.Stat(filepath.Join(root, "cmd", "product-mcp")); !os.IsNotExist(err) {
		t.Errorf("cmd/product-mcp survived the rename — the placeholder must become the product's name")
	}
	// cmd/web carries no project name and must not move.
	if _, err := os.Stat(filepath.Join(root, "cmd", "web", "main.go")); err != nil {
		t.Errorf("cmd/web moved during rename: %v", err)
	}
}

// TestRenameConsumerMCPToolNames pins the tool-list identity. An agent
// connecting to two products must be able to tell their tools apart, so the
// placeholder `product_describe` cannot survive a scaffold.
func TestRenameConsumerMCPToolNames(t *testing.T) {
	dir := t.TempDir()
	// renameIdentity reads the module path from go.mod, so the tree must look
	// like a checkout for the rename to have a name to substitute.
	gomod := "module github.com/calionauta/gogogo\n\ngo 1.27.4\n"
	if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte(gomod), 0o600); err != nil {
		t.Fatal(err)
	}
	src := filepath.Join(dir, filepath.FromSlash(shapekit.CmdProductMCP))
	if err := os.MkdirAll(src, 0o755); err != nil {
		t.Fatal(err)
	}
	// Spacing matters: the identity rewrite matches the literal
	// `Name:    "product"` as gofmt renders it in the real file.
	body := "srv := mcp.NewServer(&mcp.Implementation{\n\t\tName:    \"product\",\n\t})\n" +
		"mcp.AddTool(srv, &mcp.Tool{Name: \"product_describe\"})\n" +
		"mcp.AddTool(srv, &mcp.Tool{Name: \"product_invoke\"})\n"
	path := filepath.Join(src, "main.go")
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := renameTree(dir, "acme-portal", "acme"); err != nil {
		t.Fatal(err)
	}
	raw, err := os.ReadFile(filepath.Join(dir, "cmd", "acme-portal-mcp", "main.go"))
	if err != nil {
		t.Fatal(err)
	}
	got := string(raw)
	for _, want := range []string{`"acme-portal",`, `"acme-portal_describe"`, `"acme-portal_invoke"`} {
		if !strings.Contains(got, want) {
			t.Errorf("missing %s in renamed consumer MCP:\n%s", want, got)
		}
	}
	if strings.Contains(got, `"product`) {
		t.Errorf("placeholder survived:\n%s", got)
	}
}
