// TestProvenanceRecordsWhatTheScaffoldActuallyDropped is the bug the e2e found:
// writeAgents was called with a nil drop list, so a tree that removed six slices
// still wrote `removed: none` — and then `--check` reported the deliberate
// absences as drift while the registry conformance test looked for directories
// nobody meant to keep.
func TestProvenanceRecordsWhatTheScaffoldActuallyDropped(t *testing.T) {
	dir := t.TempDir()
	writeFile(t, filepath.Join(dir, "go.mod"), "module example.com/fixture\n\ngo 1.27\n")
	plan := scaffoldPlan{
		DropRecipes: []string{"chat", "kiosk"},
		ShapeRemove: []string{"cmd/gui"},
	}
	if err := writeAgentsForPlan(context.Background(), dir, "my-app", plan); err != nil {
		t.Fatalf("writeAgentsForPlan: %v", err)
	}
	agents := readOrEmpty(t, dir, "AGENTS.md")
	for _, want := range []string{
		"removed: chat, kiosk",
		"removed-paths: cmd/gui, features/chat, features/kiosk",
	} {
		if !strings.Contains(agents, want) {
			t.Errorf("AGENTS.md is missing %q:\n%s", want, agents)
		}
	}
	if strings.Contains(agents, "removed: none") {
		t.Error("a tree that dropped slices claims it is whole")
	}
}

