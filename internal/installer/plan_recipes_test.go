// TestGeneratedImportsDoNotKeepASlice: the registration file names every unit
// until it is regenerated, and the prune regenerates it. Its import is not a
// reason to keep anything.
func TestGeneratedImportsDoNotKeepASlice(t *testing.T) {
	root := demoTree(t)
	writeFile(t, filepath.Join(root, "internal/server/units.gen.go"),
		"// Code generated by tool. DO NOT EDIT.\n\npackage server\n\n"+
			"import chat \"example.com/fixture/features/chat\"\n\nvar _ = chat.AssetPath\n")
	users, err := sliceImporters(root, "chat", nil)
	if err != nil {
		t.Fatalf("sliceImporters: %v", err)
	}
	if len(users) != 0 {
		t.Fatalf("a generated file kept the slice: %v", users)
	}
}

// TestDropMapKeyKeepsTheDeclaration is the bug the e2e found: removing the last
// `"notes": true` pair deleted the whole `var viewerModules = ...` line, and
// every reader of the map became undefined.
func TestDropMapKeyKeepsTheDeclaration(t *testing.T) {
	line := `var viewerModules = map[string]bool{"dashboard": true, "notes": true}`
	got, ok := dropMapKey(line, "notes")
	if !ok {
		t.Fatal("dropMapKey did not remove the key")
	}
	if !strings.HasPrefix(got, "var viewerModules = map[string]bool{") {
		t.Fatalf("the declaration was removed: %q", got)
	}
	if strings.Contains(got, `"notes"`) || !strings.Contains(got, `"dashboard"`) {
		t.Fatalf("wrong map after removal: %q", got)
	}
	empty, ok := dropMapKey(`var m = map[string]bool{"notes": true}`, "notes")
	if !ok || !strings.Contains(empty, "map[string]bool{}") {
		t.Fatalf("an emptied map must keep its declaration: %q", empty)
	}
}

// TestPruneRemovesDriftedFilesAndRecordsTheTombstone: a template's receipts lag
// its development, so the declared set leaves even when the hashes no longer
// match — and the receipt stays, marked removed, for units.gen.go and the data
// owner.
func TestPruneRemovesDriftedFilesAndRecordsTheTombstone(t *testing.T) {
	root := demoTree(t)
	writeFile(t, filepath.Join(root, "features/chat/x.go"), "package chat\n\n// edited\n")
	if err := pruneReferenceRecipes(options{dir: root}, []string{"chat"}, io.Discard); err != nil {
		t.Fatalf("prune: %v", err)
	}
	if _, err := os.Stat(filepath.Join(root, "features/chat/x.go")); !os.IsNotExist(err) {
		t.Error("a drifted file of a dropped slice survived")
	}
	if _, err := os.Stat(filepath.Join(root, "features/chat")); !os.IsNotExist(err) {
		t.Error("the emptied feature directory survived")
	}
	r, err := recipe.LoadReceipt(root, "chat")
	if err != nil {
		t.Fatalf("receipt: %v", err)
	}
	if r.Removed == "" {
		t.Error("the receipt was not marked removed")
	}
}

// TestListShowsARemovedSlice: after a scaffold drops a demo, `recipe list` must
// say so. A row that reads as installed sends the next reader looking for code
// that is not there.
func TestListShowsARemovedSlice(t *testing.T) {
	root := demoTree(t)
	rec, err := recipe.LoadReceipt(root, "chat")
	if err != nil {
		t.Fatal(err)
	}
	if err := rec.MarkRemoved(time.Now()); err != nil {
		t.Fatal(err)
	}
	if err := recipe.SaveReceipt(root, rec); err != nil {
		t.Fatal(err)
	}
	var buf bytes.Buffer
	if err := runRecipeList([]string{"--dir", root}, &buf); err != nil {
		t.Fatalf("recipe list: %v", err)
	}
	var chatLine string
	for line := range strings.SplitSeq(buf.String(), "\n") {
		if strings.HasPrefix(line, "chat\t") {
			chatLine = line
		}
	}
	if !strings.Contains(chatLine, "\tremoved") {
		t.Errorf("the dropped slice still reads as installed: %q", chatLine)
	}
}

// TestShapeRemovesAnImporterThatKeepsASlice: `--shape web` deletes cmd/gui, so a
// slice only cmd/gui imports must not be kept because of it. Scanning the tree
// the shape leaves is the honest question.
func TestShapeRemovesAnImporterThatKeepsASlice(t *testing.T) {
	root := demoTree(t)
	writeFile(t, filepath.Join(root, "cmd/gui/store.go"),
		"package main\n\nimport \"example.com/fixture/features/todo\"\n\nvar _ = todo.AssetPath\n")
	p := scaffoldPlan{Shape: "web"}
	if err := applyRecipeSelection(&p, options{dir: root, shape: "web", recipes: "todo"}); err != nil {
		t.Fatalf("applyRecipeSelection: %v", err)
	}
	if len(p.DropRecipes) != 1 || p.DropRecipes[0] != "todo" {
		t.Fatalf("todo should be removable under shape web, got drop=%v keep=%v", p.DropRecipes, p.KeepRecipes)
	}
}

