// Tests for the wide-surface guard. Each case lays down a throwaway module and
// drives scan(), so the rule is proven against a tree whose answer is known by
// construction — not against this repo, which happens to be clean today.
package main

import (
	"os"
	"path/filepath"
	"testing"
)

// fixture is the import path of every throwaway module below. An export is
// judged only when a sibling may consume it.
const fixture = "github.com/calionauta/gogogo/fixture"

// libSym names a fixture symbol in the fixture's `lib` package.
func libSym(name string) string { return fixture + "/lib." + name }

// writeModule lays down a module root with the given files. The import path is
// THIS module's, because an export is only judged when a sibling may consume it.
func writeModule(t *testing.T, files map[string]string) string {
	t.Helper()
	root := t.TempDir()
	files["go.mod"] = "module " + fixture + "\n\ngo 1.27\n"
	for rel, body := range files {
		path := filepath.Join(root, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

// scan2 is scan with the error turned into a test failure.
func scan2(t *testing.T, root string) []finding {
	t.Helper()
	out, err := scan(root)
	if err != nil {
		t.Fatalf("scan() = %v", err)
	}
	return out
}

func classes(t *testing.T, root string) map[string]class {
	t.Helper()
	findings, err := scan(root)
	if err != nil {
		t.Fatalf("scan() = %v, want nil", err)
	}
	out := map[string]class{}
	for _, f := range findings {
		out[f.name] = f.class
	}
	return out
}

// TestExportNobodyNamesIsDead is the rule's reason to exist: `unused` skips
// exported names, and this one is not reachable from any main either.
func TestExportNobodyNamesIsDead(t *testing.T) {
	root := writeModule(t, map[string]string{
		"lib/lib.go": `package lib

// Nobody wants a broad interface.
type Board struct{}
func Orphan() int { return 1 }
func Used() int   { return 2 }
`,
		"app/app.go": `package app

import "github.com/calionauta/gogogo/fixture/lib"

func run() int { return lib.Used() }
`,
	})
	got := classes(t, root)
	for _, name := range []string{"lib.Board", "lib.Orphan"} {
		key := libSym(name[len("lib."):])
		if got[key] != classDead {
			t.Errorf("%s: class = %v, want classDead", name, got[key])
		}
	}
	// Present, not absent: scan measures every export so -depth can aggregate.
	// What must not happen is judging it as a finding.
	if got[libSym("Used")] != classConsumed {
		t.Errorf("Used: class = %v, want classConsumed (a sibling calls it)", got[libSym("Used")])
	}
}

// TestInternalOnlyIsAClassNotAFailure pins the reprieve: an export its own
// package calls is reviewed with -include-internal but never fails the gate.
func TestInternalOnlyIsAClassNotAFailure(t *testing.T) {
	root := writeModule(t, map[string]string{
		"lib/lib.go": `package lib

// Helper is exported and only this package calls it.
func Helper() int { return 1 }
func Public() int { return Helper() }
`,
		"app/app.go": `package app

import "github.com/calionauta/gogogo/fixture/lib"

func run() int { return lib.Public() }
`,
	})
	got := classes(t, root)
	if got["github.com/calionauta/gogogo/fixture/lib.Helper"] != classInternal {
		t.Errorf("Helper: class = %v, want classInternal", got["github.com/calionauta/gogogo/fixture/lib.Helper"])
	}
	if dead := deadNames(findings(t, root)); len(dead) != 0 {
		t.Errorf("deadNames() = %v, want none (internal-only is not dead)", dead)
	}
}

// TestAnotherPackagesTestIsNotAConsumer keeps a test seam from reading as
// production API that nothing uses.
func TestAnotherPackagesTestIsNotAConsumer(t *testing.T) {
	root := writeModule(t, map[string]string{
		"lib/lib.go": `package lib

// Seam exists so another package's test can drive it.
func Seam() int { return 1 }
`,
		"app/app_test.go": `package app

import (
	"testing"

	"github.com/calionauta/gogogo/fixture/lib"
)

func TestSeam(t *testing.T) { if lib.Seam() != 1 { t.Fatal("seam") } }
`,
	})
	if got := classes(t, root); got["github.com/calionauta/gogogo/fixture/lib.Seam"] != classTestOnly {
		t.Errorf("Seam: class = %v, want classTestOnly", got["github.com/calionauta/gogogo/fixture/lib.Seam"])
	}
}

// TestGeneratedFileIsNotJudged: a generator's output has no author to fix it,
// so a finding there would be unactionable by construction.
func TestGeneratedFileIsNotJudged(t *testing.T) {
	root := writeModule(t, map[string]string{
		"lib/gen.go": `// Code generated by fakegen. DO NOT EDIT.

package lib

func FromGenerator() int { return 1 }
`,
		"lib/lib.go": `package lib

func Kept() int { return 1 }
`,
		"app/app.go": `package app

import "github.com/calionauta/gogogo/fixture/lib"

func run() int { return lib.Kept() }
`,
	})
	if got := classes(t, root); got[libSym("FromGenerator")] != classConsumed {
		t.Errorf("FromGenerator: class = %v, want absent from the report (generated)",
			got[libSym("FromGenerator")])
	}
}

// TestMainPackageExportsAreNotJudged: a `main` cannot be imported, so its
// exports are linker handles (-X main.Version), not promises to a caller.
func TestMainPackageExportsAreNotJudged(t *testing.T) {
	root := writeModule(t, map[string]string{
		"cmd/web/main.go": `package main

// Version is injected with -ldflags -X, never imported.
var Version = "dev"

func main() { _ = Version }
`,
	})
	if got := classes(t, root); len(got) != 0 {
		t.Errorf("classes = %v, want none (package main is not a library)", got)
	}
}

// TestMethodsAndFieldsAreOutOfScope documents the boundary this gate shares
// with `iface`: a method's consumer is an interface, not a call site.
func TestMethodsAndFieldsAreOutOfScope(t *testing.T) {
	root := writeModule(t, map[string]string{
		"lib/lib.go": `package lib

type Thing struct{ Value int }

func (t Thing) Method() int { return t.Value }
`,
		"app/app.go": `package app

import "github.com/calionauta/gogogo/fixture/lib"

func run() int { return lib.Thing{Value: 1}.Method() }
`,
	})
	// The type is measured (it is exported and reachable); its METHOD and its
	// FIELD must not appear as findings of their own. Asserting on the judged
	// set, not on an empty map, is what makes this test able to fail.
	if got := deadNames(judge(findings(t, root))); len(got) != 0 {
		t.Errorf("dead = %v, want none (methods and fields are not judged)", got)
	}
}

// TestTaggedFileCountsAsAConsumer is the fail-open rule: a file excluded from
// this host's build (here: `//go:build never`) still proves the export has a
// caller, and a false "dead" is the one error a gate must not make.
func TestTaggedFileCountsAsAConsumer(t *testing.T) {
	root := writeModule(t, map[string]string{
		"lib/lib.go": `package lib

func ForOtherPlatform() int { return 1 }
`,
		"app/app.go": "package app\n\nfunc run() int { return 0 }\n",
		"app/tagged.go": `//go:build never

package app

import "github.com/calionauta/gogogo/fixture/lib"

func other() int { return lib.ForOtherPlatform() }
`,
	})
	if got := classes(t, root); got[libSym("ForOtherPlatform")] != classConsumed {
		t.Errorf("ForOtherPlatform: class = %v, want classConsumed (a tagged file consumes it)",
			got[libSym("ForOtherPlatform")])
	}
}

func findings(t *testing.T, root string) []finding {
	t.Helper()
	out, err := scan(root)
	if err != nil {
		t.Fatalf("scan() = %v, want nil", err)
	}
	return out
}

// TestAllowlistRoundTripsThroughTheFile: the baseline is what makes the gate
// adoptable on a tree with 26 known entries, so the trim/reattach of the module
// prefix has to survive a write/read cycle.
func TestAllowlistRoundTripsThroughTheFile(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "allow")
	want := []string{
		"internal/nats.PublishEvent",
		"internal/recipe.HashFile",
	}
	if err := writeAllow(path, []string{modulePath + "/" + want[0], modulePath + "/" + want[1]}); err != nil {
		t.Fatalf("writeAllow() = %v", err)
	}
	got, err := readAllow(path)
	if err != nil {
		t.Fatalf("readAllow() = %v", err)
	}
	for i := range want {
		if got[i] != modulePath+"/"+want[i] {
			t.Errorf("readAllow()[%d] = %q, want %q", i, got[i], modulePath+"/"+want[i])
		}
	}
}

// TestStaleEntryIsReported: a baseline that silently tolerates a removed
// symbol would let the same symbol come back unnoticed.
func TestStaleEntryIsReported(t *testing.T) {
	allow := []string{modulePath + "/lib.Gone", modulePath + "/lib.StillDead"}
	got := staleAllow(allow, []finding{
		{name: modulePath + "/lib.StillDead", class: classDead},
	})
	if len(got) != 1 || got[0] != modulePath+"/lib.Gone" {
		t.Errorf("staleAllow() = %v, want only lib.Gone", got)
	}
}

// TestThisTreeIsClean drives the gate over the real module: the baseline in
// .surface-allow must match the tree exactly. A failure here means someone
// added an export with no consumer (add it deliberately, or unexport it), or
// removed one (re-run -update-allow) — both are diffs a reviewer wants to see.
func TestThisTreeIsClean(t *testing.T) {
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	found, err := scan(root)
	if err != nil {
		t.Fatalf("scan(%q) = %v", root, err)
	}
	allow, err := readAllow(filepath.Join(root, ".surface-allow"))
	if err != nil {
		t.Fatalf("readAllow() = %v", err)
	}
	if stale := staleAllow(allow, found); len(stale) > 0 {
		t.Errorf("allowlisted but no longer dead (re-run -update-allow): %v", stale)
	}
	if fresh := subtracting(deadNames(found), allow); len(fresh) > 0 {
		t.Errorf("new export(s) with no consumer outside their package: %v", fresh)
	}
}

// TestSurfaceRowsAggregatesTheMeasurement pins the -depth report: it must count
// exports and outside consumers per package, split the rest into WHY, and sort
// worst ratio first. Without the why-columns a low ratio is distrusted rather
// than read.
func TestSurfaceRowsAggregatesTheMeasurement(t *testing.T) {
	// OwnOnly is called from ANOTHER package's file but with the owner's own
	// import path, which is the only shape that survives: ownPkg is derived
	// from the file's directory, and the fixture module is one segment deeper
	// than modulePath. The real tree has no such offset (see
	// TestOwnPackageUseIsCredited, which pins the real shape).
	root := writeModule(t, map[string]string{
		"lib/lib.go": `package lib

func Consumed() int { return 1 }
func NoOne() int    { return 3 }
func OwnOnly() int  { return 2 }
func TestSeam() int { return 4 }
`,
		"app/app_test.go": `package app

import (
	"testing"

	"github.com/calionauta/gogogo/fixture/lib"
)

func TestSeamIsReachable(t *testing.T) {
	if lib.TestSeam() != 4 {
		t.Fatal("seam")
	}
}
`,
		"app/app.go": `package app

import "github.com/calionauta/gogogo/fixture/lib"

func run() int { return lib.Consumed() }
`,
	})
	rows := surfaceRows(scan2(t, root), 3)
	var lib *surfaceRow
	for i := range rows {
		if rows[i].pkg == fixture+"/lib" {
			lib = &rows[i]
		}
	}
	if lib == nil {
		t.Fatalf("no row for lib in %+v", rows)
	}
	if lib.export != 4 || lib.used != 1 {
		t.Errorf("lib: export=%d used=%d, want 4 and 1", lib.export, lib.used)
	}
	if lib.dead != 2 {
		t.Errorf("lib: dead=%d, want 2 (NoOne, OwnOnly from outside)", lib.dead)
	}
	// A name only another package's TEST names is a seam, not a consumer: it
	// must land in test, never in used, or a test-only export inflates the
	// depth ratio and looks healthier than it is.
	if lib.test != 1 {
		t.Errorf("lib: test=%d, want 1 (TestSeam)", lib.test)
	}
}

// TestJudgeRunsBeforeTheAllowlist pins the ordering bug this fixed: -update-allow
// used to write the UNJUDGED list, so the first baseline on a real tree would
// have accepted 500+ live exports as debt.
func TestJudgeRunsBeforeTheAllowlist(t *testing.T) {
	all := []finding{
		{name: "p.Consumed", class: classConsumed},
		{name: "p.Dead", class: classDead},
		{name: "p.Own", class: classInternal},
	}
	got := deadNames(judge(all))
	if len(got) != 1 || got[0] != "p.Dead" {
		t.Fatalf("deadNames(judge()) = %v, want [p.Dead]", got)
	}
}

// TestOwnPackageUseIsCredited pins the unqualified-use shape against the REAL
// tree, because a fixture cannot reproduce it: ownPkg is derived from the
// file's directory relative to the module root, so a throwaway module one
// segment below modulePath resolves to a package that does not exist. The real
// tree IS the fixture for this rule — internal/queue/jobattrs_test.go calls Job
// with no qualifier.
func TestOwnPackageUseIsCredited(t *testing.T) {
	root, err := filepath.Abs("../..")
	if err != nil {
		t.Fatal(err)
	}
	got := classes(t, root)
	// Job is a struct type used unqualified by its own package's test. It must
	// come out consumed, or every tested-but-unexported type reads as dead.
	if c := got[modulePath+"/internal/queue.Job"]; c != classConsumed && c != classInternal {
		t.Errorf("internal/queue.Job: class = %v, want consumed or internal (its own test names it)", c)
	}
	// DecodeJob is used by the owner's test AND by handlers: never a finding.
	if c := got[modulePath+"/internal/queue.DecodeJob"]; c == classDead {
		t.Errorf("internal/queue.DecodeJob: class = classDead, want consumed")
	}
}
