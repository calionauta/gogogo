// TestMethodsCatchesAnUncalledExport pins the gap this file exists for: a
// method on an exported type that nothing selects and no interface requires is
// invisible to deadcode (methods are not free functions), to golangci's
// `unused` (it skips exported names) and to `iface` (interface method sets).
func TestMethodsCatchesAnUncalledExport(t *testing.T) {
	root := writeModule(t, map[string]string{
		"lib/lib.go": `package lib

type T struct{}

func (T) Called() int   { return 1 }
func (T) Uncalled() int { return 2 }

func use() int { return T{}.Called() }
`,
		"app/app.go": `package app

func run() int { return 0 }
`,
	})
	got := gapNames(t, root)
	if !strings.Contains(strings.Join(got, " "), "lib.T.Uncalled") {
		t.Errorf("gaps = %v, want lib.T.Uncalled", got)
	}
	for _, g := range got {
		if strings.Contains(g, "T.Called") {
			t.Errorf("gaps = %v, must not contain a selected method", got)
		}
	}
}

// TestMethodsSparesAnInterfaceImplementation: the method is never selected by
// name, because a caller goes through the interface. Reporting it would mark
// every implementation in the module dead.
func TestMethodsSparesAnInterfaceImplementation(t *testing.T) {
	root := writeModule(t, map[string]string{
		"lib/lib.go": `package lib

type Talker interface{ Talk() string }

type Dog struct{}

func (Dog) Talk() string { return "woof" }

func use(t Talker) string { return t.Talk() }
`,
		"app/app.go": `package app

func run() int { return 0 }
`,
	})
	if got := gapNames(t, root); len(got) != 0 {
		t.Errorf("gaps = %v, want none (Dog.Talk satisfies Talker)", got)
	}
}

// TestMethodsSparesATestOnlySeam: the loader runs without Tests, so a method
// named only by its own package's test appears in no Selections. Crediting the
// test is what keeps a real seam out of the report.
func TestMethodsSparesATestOnlySeam(t *testing.T) {
	root := writeModule(t, map[string]string{
		"lib/lib.go": `package lib

type T struct{}

func (T) ForTests() int { return 1 }
`,
		"lib/lib_test.go": `package lib

import "testing"

func TestX(t *testing.T) {
	if (T{}).ForTests() != 1 {
		t.Fatal("no")
	}
}
`,
		"app/app.go": `package app

func run() int { return 0 }
`,
	})
	if got := gapNames(t, root); len(got) != 0 {
		t.Errorf("gaps = %v, want none (its own test selects it)", got)
	}
}

// TestMethodsSkipsGenerated pins that a generated method set (a builder, a
// getter) is not hand-written surface: it is regenerated, not deleted.
func TestMethodsSkipsGenerated(t *testing.T) {
	root := writeModule(t, map[string]string{
		"lib/lib.go": `// Code generated by a tool. DO NOT EDIT.

package lib

type T struct{}

func (T) FromGenerator() int { return 1 }
`,
		"app/app.go": `package app

func run() int { return 0 }
`,
	})
	for _, g := range gapNames(t, root) {
		if strings.Contains(g, "FromGenerator") {
			t.Errorf("gaps = %v, must not contain a generated method", g)
		}
	}
}

// TestMethodsDoesNotCreditASiblingByName pins the over-credit bug: crediting a
// test use by bare method NAME made A.Shared() in a test hide a dead
// B.Shared() in the same package. A test may only credit the names its own
// package declares AND the test actually selects.
func TestMethodsDoesNotCreditASiblingByName(t *testing.T) {
	root := writeModule(t, map[string]string{
		"lib/lib.go": `package lib

type A struct{}
type B struct{}

func (A) Shared() int { return 1 }
func (B) Shared() int { return 2 }
`,
		"lib/lib_test.go": `package lib

import "testing"

func TestX(t *testing.T) { _ = (A{}).Shared() }
`,
		"app/app.go": `package app

func run() int { return 0 }
`,
	})
	got := gapNames(t, root)
	joined := strings.Join(got, " ")
	if !strings.Contains(joined, "lib.B.Shared") {
		t.Errorf("gaps = %v, want lib.B.Shared (only A.Shared is used)", got)
	}
	if strings.Contains(joined, "lib.A.Shared") {
		t.Errorf("gaps = %v, must not accuse the method its test selects", got)
	}
}

// TestMethodsDoesNotCreditAcrossPackages pins the other half: a test in package
// foo must not credit a method declared in package bar just because the names
// match. That breadth is what turns the report into a rubber stamp.
func TestMethodsDoesNotCreditAcrossPackages(t *testing.T) {
	root := writeModule(t, map[string]string{
		"lib/lib.go": `package lib

type T struct{}

func (T) Shared() int { return 1 }
`,
		"other/other.go": `package other

type S struct{}

func (S) Shared() int { return 1 }
`,
		"other/other_test.go": `package other

import "testing"

func TestX(t *testing.T) { _ = (S{}).Shared() }
`,
		"app/app.go": `package app

func run() int { return 0 }
`,
	})
	got := gapNames(t, root)
	if !strings.Contains(strings.Join(got, " "), "lib.T.Shared") {
		t.Errorf("gaps = %v, want lib.T.Shared (a test in another package must not credit it)", got)
	}
}

func gapNames(t *testing.T, root string) []string {
	t.Helper()
	_, pkgs, err := load(root, true)
	if err != nil {
		t.Fatalf("load() = %v", err)
	}
	gaps := methodGaps(pkgs)
	out := make([]string, 0, len(gaps))
	for _, g := range gaps {
		out = append(out, strings.TrimPrefix(g.name, fixture+"/"))
	}
	return out
}

// TestMethodsUnexportedReceiverIsInternal pins that a method on an unexported
// type is never reported: it is reachable only from its own package, so "no
// outside consumer" is its normal state, not a finding. Reporting it would bury
// the real ones.
func TestMethodsUnexportedReceiverIsInternal(t *testing.T) {
	root := writeModule(t, map[string]string{
		"lib/lib.go": `package lib

type hidden struct{}

func (hidden) Exported() int { return 1 }
`,
		"app/app.go": `package app

func run() int { return 0 }
`,
	})
	if got := gapNames(t, root); len(got) != 0 {
		t.Errorf("gaps = %v, want none (unexported receiver is internal)", got)
	}
}

// TestMethodsReportsAPromotedMethodOnce pins that an exported method on an
// exported EMBEDDED type is its own candidate, keyed by the type that declares
// it, not by the outer struct. Reporting it under both would double every
// embedder in the tree.
func TestMethodsReportsAPromotedMethodOnce(t *testing.T) {
	root := writeModule(t, map[string]string{
		"lib/lib.go": `package lib

type Inner struct{}

func (Inner) Hidden() int { return 1 }

type Outer struct{ Inner }
`,
		"app/app.go": `package app

func run() int { return 0 }
`,
	})
	got := gapNames(t, root)
	if len(got) != 1 || !strings.Contains(got[0], "lib.Inner.Hidden") {
		t.Errorf("gaps = %v, want exactly lib.Inner.Hidden", got)
	}
}

// TestMethodsHandlesGenericReceiver pins that a generic receiver does not panic
// and is still reported: T[P].M has no *types.Named receiver instantiation, and
// dropping it silently would make generic API invisible to the gate.
func TestMethodsHandlesGenericReceiver(t *testing.T) {
	root := writeModule(t, map[string]string{
		"lib/lib.go": `package lib

type T[P any] struct{ v P }

func (x T[P]) Val() P { return x.v }
`,
		"app/app.go": `package app

func run() int { return 0 }
`,
	})
	got := gapNames(t, root)
	if len(got) != 1 || !strings.Contains(got[0], "lib.T.Val") {
		t.Errorf("gaps = %v, want exactly lib.T.Val", got)
	}
}
